"""Convert NASA OSDR OSD-575 (SpaceX Inspiration4, serum comprehensive metabolic panel, CC0) into
backend/data/crew_reference_osd575.json. Offline, stdlib only. Re-runnable.

Run from backend/:  python scripts/import_osd575.py

Reference only: the app shows these values as they are in the file (value strings, the file's units and the lab's
reference range), with no status colours and no interpretation. Only glucose is converted, and only to follow the
user's mmol/L / mg/dL toggle (factor from questionnaire.json entry_limits.mgdl_per_mmol), in the browser.
Kept: GLUCOSE, SODIUM, POTASSIUM at every timepoint. `display` picks the timepoints shown as "before flight" and
"after flight" (the ones closest to the flight); change it here to show others.
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT.parent / "data" / "raw" / "nasa" / "osd575" / "LSDS-8_Comprehensive_Metabolic_Panel_CMP.upload_SUBMITTED.csv"
OUT = ROOT / "data" / "crew_reference_osd575.json"
ANALYTES = {"glucose": "GLUCOSE", "sodium": "SODIUM", "potassium": "POTASSIUM"}
LABELS = {"glucose": "Glucose", "sodium": "Sodium", "potassium": "Potassium"}
DISPLAY = {"pre_flight": "L-3", "post_flight": "R+1"}


def order(tp: str) -> int:
    """L-92 < L-44 < L-3 < R+1 < R+45 < ..."""
    return -int(tp[2:]) if tp.startswith("L-") else int(tp[2:])


def main() -> int:
    if not RAW.exists():
        print(f"missing {RAW}")
        return 1
    with RAW.open(newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    crew = sorted({(r["SUBJECT_ID"], r["SEX"]) for r in rows})
    timepoints = sorted({r["timepoint"] for r in rows}, key=order)
    for key in DISPLAY.values():
        if key not in timepoints:
            print(f"timepoint {key} is not in the file ({timepoints})")
            return 1
    analytes = {}
    for key, name in ANALYTES.items():
        mine = [r for r in rows if r["ANALYTE"] == name]
        units = {r["UNITS"] for r in mine}
        ranges = {(r["RANGE_MIN"], r["RANGE_MAX"]) for r in mine}
        if len(units) != 1 or len(ranges) != 1:  # one unit and one lab range per analyte, or stop
            print(f"{name}: more than one unit or range in the file: {units} {ranges}")
            return 1
        lo, hi = ranges.pop()
        values: dict[str, dict[str, str]] = {cid: {} for cid, _ in crew}
        for r in mine:
            values[r["SUBJECT_ID"]][r["timepoint"]] = r["VALUE"]  # the file's string, unchanged
        analytes[key] = {"name": name, "label": LABELS[key], "units": units.pop(), "range": [lo, hi], "values": values}
    q = json.loads((ROOT / "data" / "questionnaire.json").read_text(encoding="utf-8"))
    data = {
        "_status": "REAL reference data, shown as is (no status colours, no interpretation). Generated by "
                   "scripts/import_osd575.py; do not edit by hand.",
        "source": "NASA OSDR OSD-575, Inspiration4 (4 civilian crew, 3-day flight)",
        "dataset": "Comprehensive metabolic panel (serum), SpaceX Inspiration4",
        "licence": "CC0",
        "url": "https://osdr.nasa.gov/bio/repo/data/studies/OSD-575",
        "file": RAW.name,
        "crew": [{"id": cid, "sex": sex} for cid, sex in crew],
        "timepoints": timepoints,
        "timepoint_note": "L-n = n days before launch, R+n = n days after return (the file's own labels).",
        "display": DISPLAY,
        "mgdl_per_mmol": q["entry_limits"]["mgdl_per_mmol"],
        "analytes": analytes,
    }
    OUT.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT.parent)}: {len(crew)} crew, timepoints {timepoints}, "
          f"shown {DISPLAY['pre_flight']} vs {DISPLAY['post_flight']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
